def main():
    path = sys.argv[1]
    lines = open(path, encoding="utf-8").read().splitlines()
    out = [lines[0]]
    miss = []
    for ln in lines[1:]:
        f = ln.split("\t")
        while len(f) < 4:
            f.append("")
        va, cat, orig = f[0], f[1], f[2]
        if orig in SKIP_EXTRA:
            cat, zh = "SKIP", ""
        elif orig in KEEP:
            zh = orig
        elif orig in T:
            zh = T[orig]
        elif cat == "SKIP":
            zh = ""
        else:
            zh = ""
            miss.append(orig)
        out.append("\t".join([va, cat, orig, zh]))
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    total = sum(1 for l in out[1:] if l.split("\t")[1] == "GAME")
    done = sum(1 for l in out[1:] if l.split("\t")[1] == "GAME" and l.split("\t")[3])
    print(f"GAME: {done}/{total} 已譯;未譯 {len(miss)}")
    for m in miss[:30]:
        print("  MISS:", repr(m))


if __name__ == "__main__":
    main()
